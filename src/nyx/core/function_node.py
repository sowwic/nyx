import inspect
import logging
import re
import types
import typing

from .node import Node
from .plugin_subsystem.registry import NYX_REGISTRY
from ..static.enums import CoreDatatypes, CoreNodeComponents

LOGGER = logging.getLogger(__name__)

FUNCTION_NODE_ICON = ":/icons/function"
RETURN_COMPONENT_NAME = "return"


class FunctionNode(Node):
    """Flow node calling a python function with its components as arguments.

    Subclasses are generated by `create_function_node_class`: there is a value
    component for every parameter of the function and one for its return value.

    Attributes:
        FUNCTION: function the node calls
        FUNCTION_TYPE_ID: type id of the generated node type
        PARAMETERS: parameters of the function that get a component
        RETURN_ANNOTATION: type hint of the return value
        PARAMETER_DESCRIPTIONS: descriptions of the parameters, from the `Args:` section
            of the docstring of the function
        RETURN_DESCRIPTION: description of the return value, from the `Returns:` section
            of the docstring or else its first line
    """

    FUNCTION: typing.Callable | None = None
    FUNCTION_TYPE_ID = ""
    PARAMETERS: tuple[inspect.Parameter, ...] = ()
    RETURN_ANNOTATION: typing.Any = inspect.Signature.empty
    PARAMETER_DESCRIPTIONS: typing.ClassVar[dict[str, str]] = {}
    RETURN_DESCRIPTION = ""
    FUNCTION_TAGS: typing.ClassVar[frozenset[str]] = frozenset()
    PARAMETER_HINTS: typing.ClassVar[dict[str, typing.Any]] = {}

    @classmethod
    def get_type_id(cls) -> str:
        """str: node type id."""
        return cls.FUNCTION_TYPE_ID

    @classmethod
    def get_type_display_name(cls) -> str:
        """str: name shown in the UI, the words of the function name capitalized."""
        return cls.DEFAULT_NAME.replace("_", " ").title()

    @classmethod
    def get_description(cls) -> str:
        """str: first paragraph of the docstring of the function."""
        return (inspect.getdoc(cls.FUNCTION) or "").split("\n\n")[0].replace("\n", " ")

    @classmethod
    def get_type_icon(cls) -> str:
        """str: resource path of the function icon."""
        return FUNCTION_NODE_ICON

    @classmethod
    def get_tags(cls) -> set[str]:
        """set[str]: node tags."""
        return {"function", *cls.FUNCTION_TAGS}

    def setup(self):
        """Add the flow, parameter and return components."""
        self.flow_cpnt = self.components_model.create_component(CoreNodeComponents.FLOW)
        self.flow_cpnt.name = "flow"
        self.flow_cpnt.readable = True
        self.flow_cpnt.writable = True
        self.components_model.add_component(self.flow_cpnt)

        self.parameter_cpnts = {}
        for parameter in self.PARAMETERS:
            component = self.components_model.create_component(CoreNodeComponents.VALUE)
            component.name = parameter.name
            component.writable = True
            component.is_editable = True
            if description := self.PARAMETER_DESCRIPTIONS.get(parameter.name):
                component.description = description
            component.set_datatype(
                find_datatype_id(self.PARAMETER_HINTS.get(parameter.name))
            )
            if parameter.default is not inspect.Parameter.empty:
                component.default_value = parameter.default
                component.push_value(parameter.default)
            self.components_model.add_component(component)
            self.parameter_cpnts[parameter.name] = component

        self.return_cpnt = self.components_model.create_component(
            CoreNodeComponents.VALUE
        )
        self.return_cpnt.name = RETURN_COMPONENT_NAME
        self.return_cpnt.readable = True
        self.return_cpnt.is_editable = False
        if self.RETURN_DESCRIPTION:
            self.return_cpnt.description = self.RETURN_DESCRIPTION
        self.return_cpnt.set_datatype(find_datatype_id(self.RETURN_ANNOTATION))
        self.components_model.add_component(self.return_cpnt)

    def execute(self):
        """Call the function with the parameter values and store its result."""
        args = []
        kwargs = {}
        for parameter in self.PARAMETERS:
            value = self.parameter_cpnts[parameter.name].pull_value()
            if parameter.kind is inspect.Parameter.POSITIONAL_ONLY:
                args.append(value)
            else:
                kwargs[parameter.name] = value
        # Not evaluated: a string result would be run as an expression otherwise
        self.return_cpnt.push_value(self.FUNCTION(*args, **kwargs), evaluate=False)


def parse_docstring(docstring: str | None) -> tuple[dict[str, str], str]:
    """Read the parameter and return descriptions of a Google style docstring.

    Args:
        docstring (str | None): docstring of a function.

    Returns:
        tuple[dict[str, str], str]: descriptions of the parameters by name, and the
            description of the return value: the `Returns:` section if there is one,
            else the first line of the docstring.
    """
    text = inspect.cleandoc(docstring or "")
    summary = text.split("\n", 1)[0].strip()
    arguments: dict[str, str] = {}
    returns = ""
    section = ""
    name = ""
    for line in text.splitlines()[1:]:
        stripped = line.strip()
        header = re.fullmatch(r"(Args|Arguments|Returns|Raises|Yields):", stripped)
        if header and not line.startswith(" "):
            section, name = header.group(1), ""
            continue
        if not stripped:
            continue
        if not line.startswith(" "):
            section, name = "", ""
        elif section in ("Args", "Arguments"):
            match = re.match(r"\s+(\w+)\s*(?:\([^)]*\))?:\s*(.*)", line)
            if match and len(line) - len(line.lstrip()) <= 4:
                name = match.group(1)
                arguments[name] = match.group(2).strip()
            elif name:
                arguments[name] += " " + stripped
        elif section == "Returns":
            returns = f"{returns} {stripped}".strip()
    # A type before the text, like "str: the result"
    returns = re.sub(r"^[\w.\[\]]+(?: \| [\w.\[\]]+)*:\s+", "", returns)
    return arguments, returns or summary


def find_datatype_id(annotation: typing.Any) -> str:
    """Find the datatype for a type hint.

    Args:
        annotation (typing.Any): type hint. `X | None` counts as `X`, and a generic like
            `list[int]` as the class it is made from, `list`.

    Returns:
        str: type id of the registered datatype of the type, object if there is none.
    """
    annotation = _strip_optional(annotation)
    annotation = typing.get_origin(annotation) or annotation
    if isinstance(annotation, type):
        datatype = NYX_REGISTRY.find_datatype_for_type(annotation)
        if datatype is not None:
            return datatype.type_id
    return CoreDatatypes.OBJECT.value


def _strip_optional(annotation: typing.Any) -> typing.Any:
    """Remove `None` from a union type hint.

    Args:
        annotation (typing.Any): type hint.

    Returns:
        typing.Any: the only other type of `X | None`, the hint itself otherwise.
    """
    if typing.get_origin(annotation) in (typing.Union, types.UnionType):
        remaining = [arg for arg in typing.get_args(annotation) if arg is not type(None)]
        if len(remaining) == 1:
            return remaining[0]
    return annotation


def find_public_functions(module: types.ModuleType) -> list[typing.Callable]:
    """Get the functions defined in a module, in definition order.

    Args:
        module (types.ModuleType): module to look at.

    Returns:
        list[typing.Callable]: public functions of the module itself, not imported ones.
    """
    return [
        value
        for name, value in vars(module).items()
        if isinstance(value, types.FunctionType)
        and value.__module__ == module.__name__
        and not name.startswith("_")
    ]


def create_function_node_class(
    func: typing.Callable,
    type_id: str | None = None,
    tags: typing.Iterable[str] = (),
) -> type[FunctionNode]:
    """Generate a node type that calls a function.

    Args:
        func (typing.Callable): function to call. Its type hints choose the datatypes.
        type_id (str | None): node type id. Derived from the module and name of the
            function if omitted.
        tags (typing.Iterable[str]): tags of the node besides "function".

    Raises:
        TypeError: func is not a function with a name.

    Returns:
        type[FunctionNode]: new node class.
    """
    name = getattr(func, "__name__", None)
    if not callable(func) or not name or name == "<lambda>":
        raise TypeError(f"Can't create a node from {func!r}: not a named function")

    try:
        hints = typing.get_type_hints(func)
    except Exception:
        LOGGER.warning("Can't resolve the type hints of %s", name, exc_info=True)
        hints = dict(getattr(func, "__annotations__", {}))

    signature = inspect.signature(func)
    parameters = []
    for parameter in signature.parameters.values():
        if parameter.kind in (
            inspect.Parameter.VAR_POSITIONAL,
            inspect.Parameter.VAR_KEYWORD,
        ):
            LOGGER.warning("Parameter %s of %s is skipped", parameter.name, name)
            continue
        parameters.append(parameter)

    argument_descriptions, return_description = parse_docstring(inspect.getdoc(func))
    module = getattr(func, "__module__", "")
    qualname = getattr(func, "__qualname__", name)
    return typing.cast(
        type[FunctionNode],
        type(
            f"{name.title().replace('_', '')}Node",
            (FunctionNode,),
            {
                "DEFAULT_NAME": name,
                "FUNCTION": staticmethod(func),
                "FUNCTION_TYPE_ID": type_id or f"function:{module}.{qualname}",
                "FUNCTION_TAGS": frozenset(tags),
                "PARAMETER_DESCRIPTIONS": argument_descriptions,
                "RETURN_DESCRIPTION": return_description,
                "PARAMETERS": tuple(parameters),
                "PARAMETER_HINTS": {
                    parameter.name: hints.get(parameter.name) for parameter in parameters
                },
                "RETURN_ANNOTATION": hints.get("return", inspect.Signature.empty),
                "__doc__": inspect.getdoc(func) or f"Node calling {name}.",
            },
        ),
    )
